-- Lingo Community — historical schema
-- This text-chat schema is not used by Lingo 1.4. It is kept only as a record
-- of the removed chat feature. The live-call backend is calls_schema.sql.

create extension if not exists pgcrypto;

do $$
begin
  create type public.cefr_level as enum ('A1', 'A2', 'B1', 'B2', 'C1', 'C2', 'TOP');
exception
  when duplicate_object then null;
end $$;

-- ---------------------------------------------------------------------------
-- Profiles
-- ---------------------------------------------------------------------------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Learner',
  country text,
  avatar_sticker text not null default 'SPROUT',
  cefr_level public.cefr_level not null default 'A1',
  is_banned boolean not null default false,
  created_at timestamptz not null default now(),
  last_seen timestamptz not null default now(),
  constraint display_name_length check (char_length(display_name) between 2 and 32)
);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, display_name)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data ->> 'display_name', ''), 'Learner ' || left(new.id::text, 4))
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Guards the demonstrated CEFR level. Only the service role (an Edge
-- Function that validates an exam attempt) may promote a learner.
create or replace function public.protect_cefr_level()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.cefr_level is distinct from old.cefr_level
     and coalesce(auth.role(), '') <> 'service_role' then
    raise exception 'CEFR level can only be changed by the assessment service';
  end if;
  return new;
end;
$$;

drop trigger if exists protect_cefr_level on public.profiles;
create trigger protect_cefr_level
  before update on public.profiles
  for each row execute function public.protect_cefr_level();

-- ---------------------------------------------------------------------------
-- Match queue and conversations
-- ---------------------------------------------------------------------------
create table if not exists public.match_queue (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  cefr_level public.cefr_level not null,
  joined_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '10 minutes')
);

create table if not exists public.conversations (
  id uuid primary key default gen_random_uuid(),
  level public.cefr_level not null,
  created_at timestamptz not null default now()
);

create table if not exists public.conversation_members (
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  joined_at timestamptz not null default now(),
  primary key (conversation_id, user_id)
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  body text not null,
  created_at timestamptz not null default now(),
  constraint message_length check (char_length(body) between 1 and 1000)
);

create index if not exists messages_conversation_time_idx
  on public.messages (conversation_id, created_at);

-- ---------------------------------------------------------------------------
-- Safety and weekly leaderboard
-- ---------------------------------------------------------------------------
create table if not exists public.blocks (
  blocker_id uuid not null references public.profiles(id) on delete cascade,
  blocked_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (blocker_id, blocked_id),
  constraint cannot_block_self check (blocker_id <> blocked_id)
);

create table if not exists public.reports (
  id bigint generated by default as identity primary key,
  reporter_id uuid not null references public.profiles(id) on delete cascade,
  reported_id uuid not null references public.profiles(id) on delete cascade,
  conversation_id uuid references public.conversations(id) on delete set null,
  reason text not null default 'other',
  detail text,
  created_at timestamptz not null default now(),
  constraint report_not_self check (reporter_id <> reported_id)
);

create table if not exists public.weekly_scores (
  user_id uuid not null references public.profiles(id) on delete cascade,
  week_start date not null,
  level public.cefr_level not null,
  score smallint not null check (score between 0 and 10),
  created_at timestamptz not null default now(),
  primary key (user_id, week_start)
);

-- ---------------------------------------------------------------------------
-- Helpers
-- ---------------------------------------------------------------------------
create or replace function public.my_level()
returns public.cefr_level
language sql
stable
security definer
set search_path = public
as $$
  select cefr_level from public.profiles where id = auth.uid();
$$;

create or replace function public.is_conversation_member(conv uuid, uid uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.conversation_members
    where conversation_id = conv and user_id = uid
  );
$$;

create or replace function public.is_active_user(uid uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = uid and is_banned = false
  );
$$;

create or replace function public.is_blocked_pair(a uuid, b uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.blocks
    where (blocker_id = a and blocked_id = b)
       or (blocker_id = b and blocked_id = a)
  );
$$;

-- Creates a two-person, same-level conversation. Runs as a security definer
-- so the client cannot manufacture memberships directly.
create or replace function public.start_conversation(peer uuid)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  me uuid := auth.uid();
  my_lvl public.cefr_level;
  peer_lvl public.cefr_level;
  conv uuid;
begin
  if me is null then raise exception 'Not authenticated'; end if;
  if peer = me then raise exception 'Cannot match with yourself'; end if;
  if not public.is_active_user(me) or not public.is_active_user(peer) then
    raise exception 'This account cannot use community chat';
  end if;
  select cefr_level into my_lvl from public.profiles where id = me;
  select cefr_level into peer_lvl from public.profiles where id = peer;
  if my_lvl is null or peer_lvl is null or my_lvl <> peer_lvl then
    raise exception 'Learners must be at the same level';
  end if;
  if public.is_blocked_pair(me, peer) then
    raise exception 'This learner is blocked';
  end if;
  insert into public.conversations (level) values (my_lvl) returning id into conv;
  insert into public.conversation_members (conversation_id, user_id)
  values (conv, me), (conv, peer);
  delete from public.match_queue where user_id in (me, peer);
  return conv;
end;
$$;

create or replace function public.touch_last_seen()
returns void
language sql
security definer
set search_path = public
as $$
  update public.profiles set last_seen = now() where id = auth.uid();
$$;


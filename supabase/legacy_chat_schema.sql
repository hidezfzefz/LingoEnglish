-- Useful for the app's weekly board query.
create or replace function public.weekly_leaderboard(p_week date)
returns table (
  user_id uuid,
  display_name text,
  country text,
  cefr_level public.cefr_level,
  score smallint
)
language sql
stable
security definer
set search_path = public
as $$
  select s.user_id, p.display_name, p.country, s.level, s.score
  from public.weekly_scores s
  join public.profiles p on p.id = s.user_id
  where s.week_start = p_week
    and s.level = public.my_level()
    and p.is_banned = false
  order by s.score desc, s.created_at asc
  limit 100;
$$;

grant execute on function public.start_conversation(uuid) to authenticated;
grant execute on function public.weekly_leaderboard(date) to authenticated;
grant execute on function public.touch_last_seen() to authenticated;

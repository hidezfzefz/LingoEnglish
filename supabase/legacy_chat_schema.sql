alter table public.profiles enable row level security;
alter table public.match_queue enable row level security;
alter table public.conversations enable row level security;
alter table public.conversation_members enable row level security;
alter table public.messages enable row level security;
alter table public.blocks enable row level security;
alter table public.reports enable row level security;
alter table public.weekly_scores enable row level security;

drop policy if exists "profiles are readable" on public.profiles;
create policy "profiles are readable"
  on public.profiles for select to authenticated
  using (is_banned = false or id = auth.uid());

drop policy if exists "profiles update own" on public.profiles;
create policy "profiles update own"
  on public.profiles for update to authenticated
  using (id = auth.uid())
  with check (id = auth.uid() and is_banned = false);

drop policy if exists "queue read same level" on public.match_queue;
create policy "queue read same level"
  on public.match_queue for select to authenticated
  using (
    expires_at > now()
    and user_id <> auth.uid()
    and cefr_level = public.my_level()
    and public.is_active_user(user_id)
    and not public.is_blocked_pair(auth.uid(), user_id)
  );

drop policy if exists "queue manage own" on public.match_queue;
create policy "queue manage own"
  on public.match_queue for all to authenticated
  using (user_id = auth.uid())
  with check (
    user_id = auth.uid()
    and cefr_level = public.my_level()
    and public.is_active_user(auth.uid())
  );

drop policy if exists "conversations read membership" on public.conversations;
create policy "conversations read membership"
  on public.conversations for select to authenticated
  using (public.is_conversation_member(id, auth.uid()));

drop policy if exists "members read membership" on public.conversation_members;
create policy "members read membership"
  on public.conversation_members for select to authenticated
  using (public.is_conversation_member(conversation_id, auth.uid()));

drop policy if exists "messages read membership" on public.messages;
create policy "messages read membership"
  on public.messages for select to authenticated
  using (public.is_conversation_member(conversation_id, auth.uid()));

drop policy if exists "messages send membership" on public.messages;
create policy "messages send membership"
  on public.messages for insert to authenticated
  with check (
    sender_id = auth.uid()
    and public.is_active_user(auth.uid())
    and public.is_conversation_member(conversation_id, auth.uid())
    and not exists (
      select 1
      from public.conversation_members m
      where m.conversation_id = conversation_id
        and m.user_id <> auth.uid()
        and public.is_blocked_pair(auth.uid(), m.user_id)
    )
  );

drop policy if exists "blocks manage own" on public.blocks;
create policy "blocks manage own"
  on public.blocks for all to authenticated
  using (blocker_id = auth.uid())
  with check (blocker_id = auth.uid());

drop policy if exists "reports create own" on public.reports;
create policy "reports create own"
  on public.reports for insert to authenticated
  with check (reporter_id = auth.uid());

drop policy if exists "reports read own" on public.reports;
create policy "reports read own"
  on public.reports for select to authenticated
  using (reporter_id = auth.uid());

drop policy if exists "weekly board read cohort" on public.weekly_scores;
create policy "weekly board read cohort"
  on public.weekly_scores for select to authenticated
  using (level = public.my_level() or user_id = auth.uid());

drop policy if exists "weekly score insert own" on public.weekly_scores;
create policy "weekly score insert own"
  on public.weekly_scores for insert to authenticated
  with check (
    user_id = auth.uid()
    and level = public.my_level()
    and public.is_active_user(auth.uid())
  );


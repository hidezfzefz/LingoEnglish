    // Practice quizzes stay fast and auto-scorable; creative tasks live inside
    // lessons, where the checklist and model answer can do their job.
    val allExercises: List<Exercise> =
        lessons.flatMap { it.exercises }.filter { it.kind != ExerciseKind.WRITE } + practiceBank

    fun questionsFor(mode: PracticeMode, count: Int = 5): List<Exercise> {
        val pool = when (mode) {
            PracticeMode.DAILY -> allExercises.shuffled()
            PracticeMode.LISTENING -> allExercises.filter { it.kind == ExerciseKind.LISTENING }.shuffled()
            PracticeMode.GRAMMAR -> allExercises.filter { it.topic == Topic.GRAMMAR }.shuffled()
            PracticeMode.VOCABULARY -> allExercises.filter { it.topic == Topic.VOCABULARY }.shuffled()
        }
        return pool.take(count)
    }


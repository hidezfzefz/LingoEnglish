package com.lingo.app.data

import java.time.LocalDate

private fun slide(
    eyebrow: String,
    title: String,
    body: String,
    examples: List<Example>,
    tip: String? = null,
) = Slide(eyebrow, title, body, examples, tip)

private fun example(phrase: String, note: String) = Example(phrase, note)

private fun ex(
    id: String,
    instruction: String,
    question: String,
    options: List<String>,
    correct: Int,
    explanation: String,
    kind: ExerciseKind = ExerciseKind.CHOICE,
    audio: String? = null,
    topic: Topic = Topic.CONVERSATION,
) = Exercise(
    id = id,
    kind = kind,
    instruction = instruction,
    question = question,
    options = options,
    correctIndex = correct,
    explanation = explanation,
    audioText = audio,
    topic = topic,
)

/**
 * A guided production task. The word target keeps the learner writing; the
 * checklist and model answer make quality visible without pretending that a
 * machine can grade imagination.
 */
private fun write(
    id: String,
    instruction: String,
    question: String,
    minWords: Int,
    checklist: List<String>,
    modelAnswer: String,
    starters: List<String> = emptyList(),
    topic: Topic = Topic.CONVERSATION,
) = Exercise(
    id = id,
    kind = ExerciseKind.WRITE,
    instruction = instruction,
    question = question,
    options = emptyList(),
    correctIndex = -1,
    explanation = "",
    topic = topic,
    minWords = minWords,
    checklist = checklist,
    modelAnswer = modelAnswer,
    starters = starters,
)

